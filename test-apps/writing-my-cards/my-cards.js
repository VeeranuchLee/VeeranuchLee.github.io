/* Writing Book — My cards: the child's own word tray.
 *
 * Owner, 2026-10-21: "I think of changing the first page a bit. right now the
 * writing is fixed like this, right? I want ability to add cards from dictionary
 * and write. like 'import cards' and the import card stay on one area. and able
 * to start any of the three activities we have."
 *
 * THE AREA is the tray on the cover (app.js): the imported cards stay there,
 * counted and thumbnailed, and all three activities start from it. The ten
 * fixed levels are untouched. This file is everything behind that area:
 *
 *   state     localStorage['writing-book/my-cards/v1'] = [{w,s}] — the word and
 *             the sense id, nothing else. The picture, the clip and the
 *             writable flag are joined from CardDictionary at read time, so a
 *             regenerated snapshot re-points art and audio with no migration
 *             and no second list to drift.
 *   the rule  what a session may play: every admitted card runs Find letters
 *             and Spell it; Write it needs a–z plus the capital I (letters.js),
 *             so a card with any other capital is importable but the tray
 *             greys Write it and says why.
 *   the clip  one resolver: the local clip when the word is one of the book's
 *             own hundred (no network for a word the app already carries),
 *             otherwise the dictionary's clip — online-only, the stated voice
 *             policy (service-worker.js, THE VOICE), silence when even that is
 *             missing, like any unrendered line in this app.
 *   the picker  the Import cards overlay: search, group chips, tap to toggle,
 *             Done. Self-contained — it draws its own subtree on top of the
 *             page, removes it on exit, and never touches #screen, so it cannot
 *             disturb a session or the sticker book underneath it.
 *
 * The dictionary itself is dictionary-cards.js (generated by
 * tools/build-card-snapshot.py; held to word-book/data/dictionary.json by
 * tools/check-card-snapshot.py). If that file is absent the tray simply starts
 * empty and the picker finds nothing — the book's own ten levels are unaffected.
 *
 * Every tap is acknowledged (the estate rule): taps click, an added card chimes
 * and says its word, a full tray gets the soft retry note and a shake.
 */
(function (global) {
  'use strict';

  var STORE_KEY = 'writing-book/my-cards/v1';

  /* A sitting stays short: the book's own pages serve three to five words a
     session, and a tray holds the words the child chose today, not an album.
     One number, no dial — the owner has not asked for one. */
  var CAP = 24;

  function dict() {
    return global.CardDictionary || { cards: [], groups: [] };
  }

  function load() {
    var raw = null;
    try { raw = localStorage.getItem(STORE_KEY); } catch (e) { /* private browsing */ }
    var saved = [];
    if (raw) {
      try {
        var parsed = JSON.parse(raw);
        if (Array.isArray(parsed)) saved = parsed;
      } catch (e) { saved = []; }
    }
    /* Join against the CURRENT snapshot: a sense the dictionary no longer holds
       (renamed upstream, snapshot regenerated) must vanish, not render a card
       with no picture and no voice. */
    var bySense = {};
    dict().cards.forEach(function (c) { bySense[c.s] = c; });
    return saved.filter(function (kept) {
      return kept && kept.s && bySense[kept.s];
    });
  }

  function save(list) {
    try {
      localStorage.setItem(STORE_KEY, JSON.stringify(list));
    } catch (e) {
      /* Private browsing. The tray still works; it just will not be there
         tomorrow. Never surfaced to the child. */
    }
  }

  var cards = load();

  function find(sense) {
    for (var i = 0; i < dict().cards.length; i++) {
      if (dict().cards[i].s === sense) return dict().cards[i];
    }
    return null;
  }

  function has(sense) {
    return cards.some(function (c) { return c.s === sense; });
  }

  function entries() {
    return cards.map(function (kept) { return find(kept.s); }).filter(Boolean);
  }

  function count() { return cards.length; }

  /* 'added' | 'removed' | 'full' — the caller makes each one felt. */
  function toggle(entry) {
    if (has(entry.s)) {
      cards = cards.filter(function (c) { return c.s !== entry.s; });
      save(cards);
      return 'removed';
    }
    if (cards.length >= CAP) return 'full';
    cards = cards.concat([{ w: entry.w, s: entry.s }]);
    save(cards);
    return 'added';
  }

  /* ---- the clip --------------------------------------------------------- */

  function localSlug(word) {
    var pages = (global.WritingWords && global.WritingWords.pages) || [];
    for (var i = 0; i < pages.length; i++) {
      var words = pages[i].words;
      for (var j = 0; j < words.length; j++) {
        if (words[j].word === word) return words[j].slug;
      }
    }
    return null;
  }

  function clipFor(entry) {
    var local = localSlug(entry.w);
    if (local) return 'audio/words/' + local + '.m4a';
    return entry.aud || null;
  }

  function speak(entry) {
    var Sound = global.WritingSound;
    if (!Sound) return;
    Sound.unlock();
    Sound.voice.card({ aud: clipFor(entry) });
  }

  /* ---- what a session plays --------------------------------------------- */

  /* Page-shaped words for startCardsSession (app.js): {word, slug, pic, aud,
     writable, imported}. slug is the sense id — unique, and never an art path
     by itself, because every art read for these words goes through pic. */
  function sessionWords() {
    return entries().map(function (entry) {
      return {
        word: entry.w,
        slug: entry.s,
        pic: entry.pic,
        aud: clipFor(entry),
        writable: entry.writable !== false,
        imported: true
      };
    });
  }

  /* Write it needs a letterform for every character; find/spell take any
     admitted card. The tray asks this before it greys the button. */
  function anyNonWritable() {
    return entries().some(function (e) { return e.writable === false; });
  }

  /* Touch every selected picture once, now, while there is network: the worker
     caches same-origin 200s at run time, so each fetch here buys that card's
     offline first use. Failures are ignored — an unwarmed card simply stays
     online until the next successful fetch. Voice is NOT warmed: the book's
     stated policy leaves clips online-only (service-worker.js, THE VOICE). */
  function warm() {
    entries().forEach(function (entry) {
      if (!entry.pic || typeof global.fetch !== 'function') return;
      global.fetch(entry.pic).catch(function () { /* offline now; not fatal */ });
    });
  }

  /* ---- the Import cards picker ------------------------------------------ */

  /* An overlay, not a screen: the cover stays drawn underneath, and Done or the
     back arrow returns the child to exactly where they were. */
  function openPicker(options) {
    options = options || {};
    var Sound = global.WritingSound;
    var d = dict();

    var root = document.createElement('div');
    root.className = 'pick';

    var chips = [{ id: '', label: 'All' }].concat(d.groups);
    var group = '';      // '' = every group
    var query = '';

    root.innerHTML = '' +
      '<div class="bar">' +
      '  <button class="bar__back" id="pick-back" aria-label="Close Import cards">←</button>' +
      '  <span class="bar__title">Import cards</span>' +
      '  <span class="pick__count" id="pick-count"></span>' +
      '</div>' +
      '<div class="pick__tools">' +
      '  <input class="pick__search" id="pick-search" type="search" placeholder="Search words"' +
      '   aria-label="Search words" autocomplete="off" autocapitalize="none" spellcheck="false">' +
      '  <div class="pick__chips" id="pick-chips"></div>' +
      '</div>' +
      '<div class="pick__grid" id="pick-grid"></div>' +
      '<div class="pick__done"><button class="control" id="pick-done">Done</button></div>';
    document.body.appendChild(root);

    var grid = root.querySelector('#pick-grid');
    var countNode = root.querySelector('#pick-count');
    var chipsNode = root.querySelector('#pick-chips');
    var searchNode = root.querySelector('#pick-search');

    function feedback(name) {
      if (!Sound) return;
      Sound.unlock();
      Sound.play(name);
    }

    function renderCount() {
      countNode.textContent = count() + (count() === 1 ? ' card' : ' cards');
    }

    function renderChips() {
      chipsNode.innerHTML = chips.map(function (chip) {
        return '<button class="pick__chip' + (chip.id === group ? ' is-on' : '') +
               '" data-group="' + chip.id + '">' + chip.label + '</button>';
      }).join('');
      Array.prototype.forEach.call(chipsNode.querySelectorAll('.pick__chip'), function (chip) {
        chip.addEventListener('click', function () {
          feedback('tap');
          group = chip.getAttribute('data-group');
          renderChips();
          renderGrid();
        });
      });
    }

    function matches(entry) {
      if (group && entry.g.indexOf(group) === -1) return false;
      /* Substring, not just prefix: a child spelling "hippo" from the middle of
         the word does not know how it starts — that is the very thing they are
         here to practise. */
      if (query && entry.w.toLowerCase().indexOf(query) === -1) return false;
      return true;
    }

    function renderGrid() {
      var shown = d.cards.filter(matches);
      grid.innerHTML = shown.length ? shown.map(function (entry) {
        var inTray = has(entry.s);
        return '<button class="pickcard' + (inTray ? ' is-in' : '') + '" data-sense="' + entry.s + '"' +
               ' aria-pressed="' + inTray + '" aria-label="' + entry.w + '">' +
               '<span class="pickcard__check" aria-hidden="true">✓</span>' +
               '<span class="pickcard__pic"><img src="' + entry.pic + '" alt="" loading="lazy"></span>' +
               '<span class="pickcard__word">' + entry.w + '</span></button>';
      }).join('') : '<p class="pick__empty">No cards found.</p>';
      Array.prototype.forEach.call(grid.querySelectorAll('.pickcard'), function (button) {
        button.addEventListener('click', function () { tapCard(button); });
      });
    }

    function tapCard(button) {
      var entry = find(button.getAttribute('data-sense'));
      if (!entry) return;
      var result = toggle(entry);
      if (result === 'added') {
        /* The word is the confirmation: the card is in, and the child has
           already heard what they chose. */
        feedback('strokeGood');
        button.classList.add('is-in');
        button.setAttribute('aria-pressed', 'true');
        speak(entry);
      } else if (result === 'removed') {
        feedback('tap');
        button.classList.remove('is-in');
        button.setAttribute('aria-pressed', 'false');
      } else {
        /* Full: the soft "again" note and a shake of the counter — the same
           gentle vocabulary as a missed stroke. The card does not toggle. */
        feedback('strokeRetry');
        countNode.classList.remove('is-full');
        global.setTimeout(function () { countNode.classList.add('is-full'); }, 30);
      }
      renderCount();
    }

    /* The grid holds every matching card, so a rebuild is the expensive thing
       this screen does. Typing is debounced: each keystroke restarts a short
       timer and only the pause rebuilds, so hunting a word letter by letter
       does not rebuild two thousand buttons per key. */
    var typeTimer = null;
    searchNode.addEventListener('input', function () {
      query = searchNode.value.trim().toLowerCase();
      if (typeTimer) global.clearTimeout(typeTimer);
      typeTimer = global.setTimeout(function () {
        typeTimer = null;
        renderGrid();
      }, 160);
    });

    function close() {
      if (root.parentNode) root.parentNode.removeChild(root);
      if (options.onChange) options.onChange();
    }

    root.querySelector('#pick-back').addEventListener('click', function () {
      feedback('tap');
      close();
    });
    root.querySelector('#pick-done').addEventListener('click', function () {
      feedback('tap');
      warm();
      close();
    });

    renderCount();
    renderChips();
    renderGrid();
  }

  global.MyCards = {
    find: find,
    has: has,
    count: count,
    entries: entries,
    sessionWords: sessionWords,
    anyNonWritable: anyNonWritable,
    speak: speak,
    openPicker: openPicker,
    warm: warm,
    CAP: CAP
  };
})(window);
